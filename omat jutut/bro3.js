let students = 30;
students++;
students--;
console.log(students);

students = students + 1; //students += 1
console.log(students);

students = students - 1; //students -= 1
console.log(students);

students = students * 2; //students *= 2
console.log(students);

students = students / 2; //students /= 2
console.log(students);

students = students ** 2; //students **= 2
console.log(students);

let extraStudents = students % 3; //students %= 3
console.log(extraStudents);

/*
operation order:
1. parenthesis
2. exponents
3. multiples, division, modulus
4. +-
*/
